                        descL2T2KeyShift,
                        0,
                        descL2T2KeyShift.size,
                        null
                    ).newTemplateDependencyStructure!!
                    twoChainStructure.chainCount shouldBe 2
                    val templateId = 63
                    ((templateId + 64 - twoChainStructure.templateIdOffset) % 64 >= twoChainStructure.templateCount)
